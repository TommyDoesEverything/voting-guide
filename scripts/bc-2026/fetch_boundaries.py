"""Fetch the official boundaries of the ridings this guide covers.

The "Find my riding" box checks an address or location against these shapes
in the browser. Boundaries come from Elections BC's current provincial
electoral districts, published on the BC Data Catalogue:

    https://catalogue.data.gov.bc.ca/dataset/provincial-electoral-districts-of-british-columbia

The script writes elections/bc-2026/ridings.js, keyed by the office id in
guide.js. Shapes are simplified only to about 1 m (the file is still small); the
finder always tells people to confirm with Elections BC.

    python scripts/bc-2026/fetch_boundaries.py

Standard library only.
"""

import json
import sys
import urllib.parse
import urllib.request
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from fetch_candidates import RIDINGS  # noqa: E402  district code -> office id

WFS = "https://openmaps.gov.bc.ca/geo/pub/wfs"
LAYER = "WHSE_ADMIN_BOUNDARIES.EBC_PROV_ELECTORAL_DIST_SVW"
DATASET = "https://catalogue.data.gov.bc.ca/dataset/provincial-electoral-districts-of-british-columbia"
TOLERANCE = 0.00001  # degrees, about 1 m
OUT = Path(__file__).resolve().parents[2] / "elections" / "bc-2026" / "ridings.js"


def fetch():
    codes = ",".join(f"'{c}'" for c in RIDINGS)
    query = urllib.parse.urlencode({
        "service": "WFS", "version": "2.0.0", "request": "GetFeature",
        "typeName": LAYER, "outputFormat": "json", "srsName": "EPSG:4326",
        "CQL_FILTER": f"ED_ABBREVIATION IN ({codes})",
    })
    with urllib.request.urlopen(f"{WFS}?{query}", timeout=120) as r:
        return json.load(r)


def simplify(points, tol):
    """Douglas-Peucker on one ring of [lon, lat] points."""
    if len(points) < 4:
        return points
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        a, b = stack.pop()
        (x1, y1), (x2, y2) = points[a], points[b]
        dx, dy = x2 - x1, y2 - y1
        norm = (dx * dx + dy * dy) ** 0.5
        best, at = 0.0, None
        for i in range(a + 1, b):
            x, y = points[i]
            d = abs(dy * (x - x1) - dx * (y - y1)) / norm if norm else ((x - x1) ** 2 + (y - y1) ** 2) ** 0.5
            if d > best:
                best, at = d, i
        if at is not None and best > tol:
            keep[at] = True
            stack += [(a, at), (at, b)]
    return [p for p, k in zip(points, keep) if k]


def rings(geometry):
    """Every ring as a list of [lon, lat], rounded to 5 decimals (about 1 m).
    Holes are kept as rings too: the finder uses even-odd counting."""
    polys = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
    out = []
    for poly in polys:
        for ring in poly:
            r = simplify([[round(x, 5), round(y, 5)] for x, y in ring], TOLERANCE)
            if len(r) >= 4:
                out.append(r)
    return out


def main():
    data = fetch()
    shapes = {}
    for f in data["features"]:
        p = f["properties"]
        office = RIDINGS[p["ED_ABBREVIATION"]]
        shapes[office] = {"name": p["ED_NAME"], "rings": rings(f["geometry"])}
    missing = set(RIDINGS.values()) - set(shapes)
    if missing:
        sys.exit(f"no boundary found for {sorted(missing)}")
    out = {"fetched": date.today().isoformat(), "source": DATASET, "ridings": shapes}
    OUT.write_text(
        "// Generated by scripts/bc-2026/fetch_boundaries.py from Elections BC's electoral\n"
        "// district boundaries (BC Data Catalogue). Do not edit by hand - re-run the script.\n"
        f"window.RIDING_SHAPES = {json.dumps(out, separators=(',', ':'))};\n",
        encoding="utf-8", newline="\n",
    )
    points = sum(len(r) for s in shapes.values() for r in s["rings"])
    print(f"wrote {len(shapes)} ridings, {points} points, {OUT.stat().st_size // 1024} KB", file=sys.stderr)


if __name__ == "__main__":
    main()
